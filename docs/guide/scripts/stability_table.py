"""
Linear stability of the shelf presets and the physical defaults, with both cavity choices

    python docs/guide/scripts/stability_table.py

Writes docs/guide/tables/stability_table.md (the table of docs/guide/stability.md) and
docs/guide/tables/stability_phase_window.md (the window of second-tweezer phases that destabilises
the default 2×2 system). Every number comes from `MultiTrap.drift_eigenvalues`, through
`max_growth_rate`, `is_stable`, `least_stable_mode` and `unstable_modes`; it runs in about a minute.
"""
from pathlib import Path

import numpy as np
from scipy.optimize import brentq

from levisim.core.logger import set_console_level
from levisim.core.units import degrees, kHz, cm, mbar
from levisim.multiphysics.multitrap import MultiTrap
from levisim.multiphysics.utils import shelf
from levisim.physics.cavity import Cavity
from levisim.physics.gas import Gas

TABLES = Path(__file__).resolve().parents[1] / 'tables'

# every unstable system would log the construction WARNING; the table records them instead
set_console_level('ERROR')

CHOICES = {
    'shelf': dict(gas_kwargs=shelf.DEFAULT_gas_kwargs, cavity_kwargs=shelf.DEFAULT_cavity_kwargs),
    'defaults': dict(),
}
OFF_NODE_SHAPES = ['1×1', '2×1', '1×2', '2×2', '3×2', '1×3', '2×3', '3×3']
SYSTEMS = (
    [(f'physical defaults, {shape}', shape, None) for shape in ['1×2', '2×1', '2×2', '1×3', '3×2']]
    + [('`FORTRAN_toy_params`, 8×2', '8×2', 'FORTRAN_toy_params')]
    + [(f'`{name}`, {shape}', shape, name)
       for name in ['PHASE_EQUAL_toy_params', 'PHASE_DEPENDENT_toy_params'] for shape in shelf.PHASE_SYSTEMS]
    + [(f'`{name}`, {shape}', shape, name)
       for name in ['OFF_NODE_toy_params_pairs', 'OFF_NODE_toy_params_equal_spacing',
                    'OFF_NODE_toy_params_equal_spacing_simple'] for shape in OFF_NODE_SHAPES]
)


def build(shape, toy_name, choice, **kwargs):
    N, d = (int(_) for _ in shape.split('×'))
    if toy_name is not None:
        kwargs['toy_params'] = getattr(shelf, toy_name)
    return MultiTrap(num_traps=N, Cartesian_axes_per_trap=d, ω_range=np.array([0.0]), **CHOICES[choice], **kwargs)


def cells(mtrap):
    Ω, growth_rate = mtrap.least_stable_mode
    verdict = 'stable' if mtrap.is_stable else f'**unstable** ({len(mtrap.unstable_modes)})'
    return [verdict, f'{growth_rate:+.4g}', f'{Ω / kHz:.2f}']


def max_growth_rate_2x2(φ2, choice):
    return build('2×2', None, choice, φn_dict={2: φ2}).max_growth_rate


def phase_window(choice):
    """sign changes of max Re λ over φ2 in [0°, 360°), refined to 1e-6°"""
    φ2s = np.arange(0, 360.25, 0.25) * degrees
    rates = np.array([max_growth_rate_2x2(φ2, choice) for φ2 in φ2s])
    edges = [
        brentq(max_growth_rate_2x2, φ2s[ii], φ2s[ii + 1], args=(choice,), xtol=1e-8)
        for ii in np.flatnonzero(np.sign(rates[:-1]) != np.sign(rates[1:]))
    ]
    return edges, φ2s, rates


if __name__ == '__main__':
    gas, cavity, shelf_cavity = Gas(), Cavity(), Cavity(**shelf.DEFAULT_cavity_kwargs)
    lines = [
        '| System | shelf kwargs: verdict (growing modes) | max Re λ (s⁻¹) | mode \\|Im λ\\|/2π (kHz)'
        ' | constructor defaults: verdict (growing modes) | max Re λ (s⁻¹) | mode \\|Im λ\\|/2π (kHz) |',
        '|---|---|---|---|---|---|---|',
    ]
    for label, shape, toy_name in SYSTEMS:
        row = [label] + cells(build(shape, toy_name, 'shelf')) + cells(build(shape, toy_name, 'defaults'))
        lines.append('| ' + ' | '.join(row) + ' |')
        print('RESULT', ' | '.join(row))
    header = (
        '<!-- generated by docs/guide/scripts/stability_table.py: do not edit by hand -->\n\n'
        f'Shelf kwargs: `DEFAULT_gas_kwargs` (P = {shelf.DEFAULT_gas_kwargs["P"] / mbar:.0e} mbar) and'
        f' `DEFAULT_cavity_kwargs` (L = {shelf.DEFAULT_cavity_kwargs["L"] / cm:.3g} cm, finesse'
        f' {shelf.DEFAULT_cavity_kwargs["Finesse"]:,.0f}, Δ/2π = {shelf.DEFAULT_cavity_kwargs["Δ"] / kHz:.0f} kHz,'
        f' κ/2π = {shelf_cavity.κ / kHz:.1f} kHz).'
        f' Constructor defaults: `Gas()` (P = {gas.P / mbar:.0e} mbar) and `Cavity()` (L = {cavity.L / cm:.4g} cm,'
        f' finesse {cavity.Finesse:,.0f}, Δ/2π = {cavity.Δ / kHz:.0f} kHz, κ/2π = {cavity.κ / kHz:.1f} kHz;'
        ' in a physical `MultiTrap` the cavity is driven at the tweezer frequency).'
        ' The mode column is the frequency of the least-damped (stable) or fastest-growing (unstable) normal mode.\n\n'
    )
    (TABLES / 'stability_table.md').write_text(header + '\n'.join(lines) + '\n')

    text = ['<!-- generated by docs/guide/scripts/stability_table.py: do not edit by hand -->\n']
    for choice, name in (('shelf', 'shelf kwargs'), ('defaults', 'constructor defaults')):
        edges, φ2s, rates = phase_window(choice)
        print('RESULT window', choice, [f'{edge / degrees:.4f}' for edge in edges])
        edges_deg = [edge / degrees for edge in edges]
        pairs = [f'{a:.2f}° < φ2 < {b:.2f}°' for a, b in zip(edges_deg[::2], edges_deg[1::2])]
        at = {φ: build('2×2', None, choice, φn_dict={2: φ * degrees}) for φ in (0, 30, 90)}
        values = '; '.join(
            f'at φ2 = {φ}°: max Re λ = {m.max_growth_rate:+.4g} s⁻¹ on the mode at {m.least_stable_mode[0] / kHz:.2f} kHz'
            for φ, m in at.items()
        )
        # the window repeats every 180°, so the largest growth rate is quoted for 0 ≤ φ2 < 180°
        half = φ2s < 180 * degrees
        worst = np.argmax(rates[half])
        text.append(
            f'- **{name}**: unstable for {" and ".join(pairs) if pairs else "no φ2"} (φ1 = 0°, sampled every 0.25°'
            f' over 0-360° and refined by root finding); {values}. The largest growth rate,'
            f' {rates[worst]:+.4g} s⁻¹, is at φ2 = {φ2s[worst] / degrees:.2f}°.'
        )
    (TABLES / 'stability_phase_window.md').write_text('\n'.join(text) + '\n')
    print('\n'.join(text))
